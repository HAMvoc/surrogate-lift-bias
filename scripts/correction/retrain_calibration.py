"""Few-shot calibration on E2A (prereg addendum 1, A; exploratory): M2 R2 trained on 450 Fastback+Notchback plus k Estateback cars, tested on the fixed 225 Estateback cars.
k = 0 is the existing E2A_M2_R2_s0 run restricted to the same 225 cars. Primary endpoint: mean signed C_L,p error (counts); rule registered before the runs.
Usage: python scripts/correction/retrain_calibration.py"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT))
from scripts.diagnosis.region_errors import md  # noqa: E402
from scripts.diagnosis.pressure_coefficients import CLIP, boot, cdp  # noqa: E402
from scripts.diagnosis.physics_plots import cl  # noqa: E402

RES, CACHE = ROOT / "results", ROOT / "data" / "cache"
# (fold, seed, [(label, k, rep)]); k = 0 is the existing `{fold}_M2_R2_s{seed}` run restricted to the same 225 cars
KS = [(f"k={k}", k, 1) for k in (5, 10, 25)]
BLOCKS = [("E2A", 0, KS + [("k=10, x5", 10, 5), ("k=25, x5", 25, 5)]), ("E2A", 1, KS), ("E2A", 2, KS), ("E2B", 0, KS), ("E2C", 0, KS)]


def run_name(fold, seed, k, rep):
    return f"{fold}_M2_R2_s{seed}" + ("" if k == 0 else f"_cal{k}" + ("x5" if rep == 5 else ""))


def block(fold, seed, ks):
    ref_csv = pd.read_csv(RES / run_name(fold, 0, 5, 1) / "test_per_car.csv")
    ids = list(ref_csv.id)
    assert len(ids) == 225
    pools = [np.load(CACHE / i / "pool.npz") for i in ids]
    ref = [np.clip(p["cp"].astype(np.float64), *CLIP) for p in pools]
    one = lambda n: np.ones(len(n))
    f_d = lambda j, c: 1000 * cdp(c, pools[j]["normal"][:, 0], pools[j]["area"], ids[j])
    f_l = lambda j, c: 1000 * cl(c, pools[j]["normal"][:, 2], pools[j]["area"], ids[j], one(c))
    r_d, r_l = np.array([f_d(j, ref[j]) for j in range(225)]), np.array([f_l(j, ref[j]) for j in range(225)])
    rows, base_bias, val0 = [], None, pd.read_csv(RES / run_name(fold, seed, 0, 1) / "val_per_car.csv").rel_l2.mean()
    for label, k, rep in [("k=0", 0, 1)] + ks:
        d = RES / run_name(fold, seed, k, rep)
        if not (d / "test_pred_fp16.npy").exists():
            continue
        t = pd.read_csv(d / "test_per_car.csv")
        pr = np.load(d / "test_pred_fp16.npy", mmap_mode="r")
        pos = {i: n for n, i in enumerate(t.id)}
        sel = [pos[i] for i in ids]  # k=0 run has all 250 test cars: pick the same 225
        e_d = np.array([f_d(j, np.asarray(pr[s], np.float64)) for j, s in enumerate(sel)]) - r_d
        e_l = np.array([f_l(j, np.asarray(pr[s], np.float64)) for j, s in enumerate(sel)]) - r_l
        rel = t.set_index("id").loc[ids].rel_l2.to_numpy()
        lo, hi = boot(e_l, np.mean)
        bias = float(e_l.mean())
        base_bias = bias if k == 0 else base_bias
        val = pd.read_csv(d / "val_per_car.csv").rel_l2.mean()
        rows.append({"config": label, "k x rep": f"{k} x {rep}", "rel L2 (225 test)": f"{rel.mean():.4f}", "C_L,p bias [CI 95%]": f"{bias:+.1f} [{lo:+.1f}; {hi:+.1f}]",
                     "C_L,p MAE": f"{np.abs(e_l).mean():.1f}", "bias vs k=0": f"{100 * bias / base_bias:.0f}%", "C_D,p bias": f"{e_d.mean():+.2f}", "C_D,p MAE": f"{np.abs(e_d).mean():.2f}",
                     "val rel L2": f"{val:.4f}", "val change": f"{val - val0:+.4f}"})
        print(fold, seed, rows[-1], flush=True)
    return rows


def main():
    text = ["# Few-shot calibration (exploratory; auto-generated by `scripts/correction/retrain_calibration.py`)", "",
            "Test = fixed 225 cars of the held-out style (25 calibration cars removed from test for every k). Differences below 20 counts in C_L,p are not interpreted. `val change` = val rel L2 minus the k=0 run of the same fold/seed (registered limit +0.005).", ""]
    summary = {}  # (fold, k) -> list of (seed, ratio, val change) for k with rep 1
    for fold, seed, ks in BLOCKS:
        if not (RES / run_name(fold, seed, 0, 1) / "val_per_car.csv").exists() or not (RES / run_name(fold, 0, 5, 1) / "test_per_car.csv").exists():
            continue
        rows = block(fold, seed, ks)
        text += [f"## {fold}, seed {seed}", "", md(rows), ""]
        for r in rows[1:]:
            if r["k x rep"].endswith("x 1"):
                summary.setdefault((fold, int(r["k x rep"].split()[0])), []).append((seed, float(r["bias vs k=0"].rstrip("%")), float(r["val change"])))
    text += ["## Summary by fold and k (rep 1)", "", md([{"fold": f, "k": k, "seeds": ",".join(str(s) for s, _, _ in v), "bias vs k=0 per seed": " / ".join(f"{b:.0f}%" for _, b, _ in v),
                                                           "mean": f"{np.mean([b for _, b, _ in v]):.0f}%", "max val change": f"{max(c for _, _, c in v):+.4f}",
                                                           "all seeds <=50% and val ok": all(b <= 50 and c <= 0.005 for _, b, c in v)} for (f, k), v in sorted(summary.items())]), ""]
    (ROOT / "reports" / "calibration.md").write_text(chr(10).join(text), encoding="utf-8")


if __name__ == "__main__":
    main()
