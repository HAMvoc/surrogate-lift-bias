"""Pool (IPW) estimator vs the exact full-mesh integral for C_D,p AND C_L,p on 45 cars (15 per body style, evenly spaced), CFD labels only (exploratory; closes the lift part of the 8-car check in cdp_analysis).
Usage: python scripts/data/lift_pool_validation.py"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT))
from scripts.diagnosis.pressure_coefficients import CFG, CLIP, GEO, cdp  # noqa: E402
from scripts.diagnosis.region_errors import md  # noqa: E402
from scripts.diagnosis.physics_plots import cl  # noqa: E402
from scripts.data.preprocess import vertex_normals_and_areas  # noqa: E402


def main():
    import pyvista as pv
    ids = [i for c in "EFN" for i in [j for j in GEO.index if j[0] == c][:: 250 // 15][:15]]
    rows = []
    for sid in ids:
        m = pv.read(ROOT / "data" / "raw" / CFG["source"]["vtk_dir"] / f"{sid}.vtk")
        cp = np.clip(np.asarray(m.point_data["p"], np.float64) / (0.5 * CFG["cp"]["u_inf"] ** 2), *CLIP)
        nrm, va = vertex_normals_and_areas(m)
        w = va.astype(np.float64) * cp
        a_ref = GEO.at[sid, "frontal_area_m2"]
        ex_d, ex_l = -1000 * float((w * nrm[:, 0]).sum()) / a_ref, -1000 * float((w * nrm[:, 2]).sum()) / a_ref
        p = np.load(ROOT / "data" / "cache" / sid / "pool.npz")
        pc = np.clip(p["cp"].astype(np.float64), *CLIP)
        ip_d = 1000 * cdp(pc, p["normal"][:, 0], p["area"], sid)
        ip_l = 1000 * cl(pc, p["normal"][:, 2], p["area"], sid, np.ones(len(pc)))
        rows.append({"style": sid[0], "id": sid, "C_D,p exact": ex_d, "C_D,p pool": ip_d, "C_L,p exact": ex_l, "C_L,p pool": ip_l})
        print(rows[-1], flush=True)
    d = pd.DataFrame(rows)
    d["err D"], d["err L"] = d["C_D,p pool"] - d["C_D,p exact"], d["C_L,p pool"] - d["C_L,p exact"]
    s = d.groupby("style")[["err D", "err L"]].agg(["mean", lambda x: x.abs().max()]).round(2)
    s.columns = ["C_D,p mean err", "C_D,p max abs err", "C_L,p mean err", "C_L,p max abs err"]
    text = ["# Pool estimator vs exact mesh integral, drag and lift (exploratory; auto-generated by `scripts/data/lift_pool_validation.py`)", "",
            f"45 cars (15 per body style, evenly spaced over the 750), CFD labels only (clipped Cp), error = pool IPW estimate minus the exact sum over all mesh vertices, in counts (0.001). "
            f"Overall: C_D,p mean {d['err D'].mean():+.2f}, max abs err {d['err D'].abs().max():.2f}; C_L,p mean {d['err L'].mean():+.2f}, max abs err {d['err L'].abs().max():.2f} counts. "
            "For scale, the C_L,p bias of the models on held-out estateback is +150..+220 counts and the CFD sd across cars is about 83 counts.", "", md(s.reset_index().to_dict("records")), ""]
    (ROOT / "reports" / "lift_pool_validation.md").write_text(chr(10).join(text), encoding="utf-8")


if __name__ == "__main__":
    main()
