"""Generate splits (spec 6): E1, E2A/B/C, E2b. Split by group_id, seeded; writes data/manifests/splits/*.json + SHA256SUMS,
R1 SDF distances between cars (dist_R1.npz, reused for B1) and reports/split_report.md.
Usage: python scripts/data/make_splits.py [--seed 0]"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import torch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from src.data.grid import load_cfg  # noqa: E402

CFG = load_cfg()
MAN = ROOT / "data" / "manifests"
FRONT_X = 0.45  # L_ref: "front half of the car" for the same-front, different-rear check (spec 6.2, no. 5)
CATS = {"F": "Fastback", "N": "Notchback", "E": "Estateback"}


def distances(ids):
    """L2 between R1 SDFs (whole car and front half), n x n matrices in ids order; cached in dist_R1.npz."""
    f = MAN / "dist_R1.npz"
    if f.exists():
        z = np.load(f, allow_pickle=True)
        if list(z["ids"]) == list(ids):
            return z["full"], z["front"]
    box, nx = CFG["box"], CFG["grids"]["R1"][0]
    n_front = int((FRONT_X - box["x"][0]) / (box["x"][1] - box["x"][0]) * nx)
    v = torch.stack([torch.from_numpy(np.load(ROOT / "data" / "cache" / i / "sdf_R1.npy")).float() for i in ids])  # (n, Z, Y, X)
    out = []
    for x in (v.flatten(1), v[..., :n_front].flatten(1)):
        sq = (x * x).sum(1)
        out.append(((sq[:, None] + sq[None] - 2 * x @ x.T).clamp_min(0).sqrt()).numpy())
    np.savez(f, ids=np.array(ids), full=out[0], front=out[1])
    return out[0], out[1]


def assign(avail, cat, grp, quota, rng):
    """Pick cars for one role by per-style quota; a whole group_id goes to the same role (greedy over the shuffled order)."""
    members = {}
    for i in avail:
        members.setdefault(grp[i], []).append(i)
    order = list(members)
    rng.shuffle(order)
    left, picked = dict(quota), []
    for g in order:
        need = {}
        for i in members[g]:
            need[cat[i]] = need.get(cat[i], 0) + 1
        if all(left.get(c, 0) >= k for c, k in need.items()):
            for c, k in need.items():
                left[c] -= k
            picked += members[g]
    assert all(v == 0 for v in left.values()), f"quota not filled: {left}"
    return picked


def build(man, params, seed):
    cat = dict(zip(man.sample_id, man.category))
    grp = dict(zip(man.sample_id, man.group_id))
    ids = list(man.sample_id)
    rng = np.random.default_rng(seed)
    S = {}

    def split(train, val, test, dropped=()):
        return {"train": sorted(train), "val": sorted(val), "test": sorted(test), "dropped": sorted(dropped)}

    # E1: 200/25/25 per style
    te = assign(ids, cat, grp, {c: 25 for c in CATS.values()}, rng)
    rest = [i for i in ids if i not in set(te)]
    va = assign(rest, cat, grp, {c: 25 for c in CATS.values()}, rng)
    S["E1"] = split([i for i in rest if i not in set(va)], va, te)

    # E2A/B/C: hold out one style; val is 25 cars of each remaining style taken from train
    for name, hold in (("E2A", "Estateback"), ("E2B", "Notchback"), ("E2C", "Fastback")):
        tr = [i for i in ids if cat[i] != hold]
        va = assign(tr, cat, grp, {c: 25 for c in CATS.values() if c != hold}, rng)
        S[name] = split([i for i in tr if i not in set(va)], va, [i for i in ids if cat[i] == hold])

    # E2param (spec: E2b; renamed because Windows is case-insensitive and E2b would clash with E2B): test = top 20% PC1 of the parameter vector within each style (PCA standardised on that style alone;
    # PC1 sign chosen so that the coefficient with the largest absolute value is positive). Cars sharing a group_id with a test car are dropped from train/val.
    test = []
    for c in CATS.values():
        sub = [i for i in ids if cat[i] == c]
        x = params.loc[sub].to_numpy(float)
        x = (x - x.mean(0)) / np.where(x.std(0) > 0, x.std(0), 1.0)
        w = np.linalg.svd(x, full_matrices=False)[2][0]
        w = w * np.sign(w[np.argmax(np.abs(w))])
        pc1 = x @ w
        test += [sub[k] for k in np.argsort(-pc1)[: round(0.2 * len(sub))]]
    tg = {grp[i] for i in test}
    dropped = [i for i in ids if grp[i] in tg and i not in set(test)]
    rest = [i for i in ids if i not in set(test) and i not in set(dropped)]
    quota = {c: round(0.1 * sum(cat[i] == c for i in rest)) for c in CATS.values()}
    va = assign(rest, cat, grp, quota, rng)
    S["E2param"] = split([i for i in rest if i not in set(va)], va, test, dropped)
    return S


def report(S, man, full, front, ids, eps):
    pos = {i: k for k, i in enumerate(ids)}
    cat = dict(zip(man.sample_id, man.category))
    grp = dict(zip(man.sample_id, man.group_id))
    L = ["# Split report", "", f"Auto-generated by `scripts/data/make_splits.py`. Near-twin threshold eps = {eps:.3f} (95th percentile of the R1 SDF front-half distance between pairs sharing a group_id).", ""]
    L += ["| Split | train | val | test | dropped | test: same group as a train car | test: nearest-train front <= eps | front dist median (test) | full dist median (test) |", "|---|---|---|---|---|---|---|---|---|"]
    flags = {}
    for name, s in S.items():
        tr = [pos[i] for i in s["train"]]
        te = s["test"]
        tg = {grp[i] for i in s["train"]}
        twin = [i for i in te if grp[i] in tg]
        d_front = np.array([front[pos[i], tr].min() for i in te])
        d_full = np.array([full[pos[i], tr].min() for i in te])
        near = [i for i, d in zip(te, d_front) if d <= eps]
        flags[name] = {"twin_in_train": twin, "near_twin": near}
        L.append(f"| {name} | {len(s['train'])} | {len(s['val'])} | {len(te)} | {len(s['dropped'])} | {len(twin)} | {len(near)} | {np.median(d_front):.2f} | {np.median(d_full):.2f} |")
    L += ["", "Cars per body style:", ""]
    for name, s in S.items():
        L.append(f"- {name}: " + "; ".join(f"{r} " + ", ".join(f"{c[0]}={sum(cat[i] == c for i in s[r])}" for c in CATS.values()) for r in ("train", "val", "test")))
    return "\n".join(L) + "\n", flags


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    man = pd.read_csv(MAN / "manifest.csv")
    man = man[man.status == "ok"].reset_index(drop=True)
    pc = pd.read_csv((ROOT / CFG["source"]["params_csv"]).resolve()).set_index("Experiment")
    params = pc[[c for c in pc.columns if not c.startswith(("Average", "Std"))]]
    assert params.shape[1] == 23
    ids = list(man.sample_id)
    full, front = distances(ids)
    grp = dict(zip(man.sample_id, man.group_id))
    pos = {i: k for k, i in enumerate(ids)}
    twin = [front[pos[i], pos[j]] for i in ids for j in ids if i < j and grp[i] == grp[j]]
    eps = float(np.quantile(twin, 0.95))

    S = build(man, params, a.seed)
    text, flags = report(S, man, full, front, ids, eps)
    out = MAN / "splits"
    out.mkdir(exist_ok=True)
    sums = {}
    for name, s in S.items():
        body = {"name": name, "seed": a.seed, **s, "leak_flags": flags[name], "near_twin_eps_front": eps}
        raw = json.dumps(body, indent=1, sort_keys=True)
        (out / f"{name}.json").write_text(raw)
        sums[f"{name}.json"] = hashlib.sha256(raw.encode()).hexdigest()
    (out / "SHA256SUMS.json").write_text(json.dumps(sums, indent=1))
    (ROOT / "reports" / "split_report.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
