"""Impact of the non-exact area-proportionality of the 100k point pool (found while building scripts/diagnosis/pressure_coefficients.py).
(1) Validation on a few cars: area-weighted mean and mean square of the reference Cp over the FULL mesh vs the plain pool mean vs the inverse-probability-weighted (IPW) pool estimate.
(2) Impact on the primary metric: per-car rel L2 recomputed with IPW weights w = area / pi (pi = 1 - exp(-lambda * area)) instead of the plain mean, for M2 (3 seeds) and B2 on E2A/B/C,
    and on the paired M2 - B2 differences. Predictions are only stored at pool points, so B0/B1 and M2-on-E1 cannot be recomputed.
Usage: python scripts/data/pool_weight_impact.py [--out reports/pool_weight_impact.md]"""
import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT))
from src.data.grid import load_cfg  # noqa: E402
from src.evaluation.metrics import bootstrap_ci  # noqa: E402

CFG = load_cfg()
CLIP = tuple(CFG["target"]["cp_clip"])
GEO = pd.read_csv(ROOT / "data" / "manifests" / "car_geometry.csv").set_index("sample_id")
RES = ROOT / "results"
FOLDS = {"E2A": "Estateback", "E2B": "Notchback", "E2C": "Fastback"}


def weights(area, sid):
    return area / (1 - np.exp(-GEO.at[sid, "incl_rate_per_m2"] * area))


def validate(ids):
    import pyvista as pv
    from scripts.data.preprocess import vertex_normals_and_areas
    rows = []
    for sid in ids:
        m = pv.read(ROOT / "data" / "raw" / CFG["source"]["vtk_dir"] / f"{sid}.vtk")
        cp = np.clip(np.asarray(m.point_data["p"], np.float64) / (0.5 * CFG["cp"]["u_inf"] ** 2), *CLIP)
        va = vertex_normals_and_areas(m)[1].astype(np.float64)
        ex = (float((va * cp).sum() / va.sum()), float((va * cp ** 2).sum() / va.sum()))
        p = np.load(ROOT / "data" / "cache" / sid / "pool.npz")
        pc, pa = np.clip(p["cp"].astype(np.float64), *CLIP), p["area"].astype(np.float64)
        w = weights(pa, sid)
        nv = (float(pc.mean()), float((pc ** 2).mean()))
        ip = (float((w * pc).sum() / w.sum()), float((w * pc ** 2).sum() / w.sum()))
        rows.append({"id": sid, "exact E[cp^2]": ex[1], "naive": nv[1], "IPW": ip[1], "naive err %": 100 * (nv[1] / ex[1] - 1), "IPW err %": 100 * (ip[1] / ex[1] - 1),
                     "exact E[cp]": ex[0], "naive E[cp]": nv[0], "IPW E[cp]": ip[0]})
    return pd.DataFrame(rows)


def rel_l2(pred, ref, w):
    return float(np.sqrt((w * (pred - ref) ** 2).sum() / (w * ref ** 2).sum()))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "reports" / "pool_weight_impact.md"))
    a = ap.parse_args()
    ids = list(GEO.index[:: len(GEO) // 12])[:12]
    v = validate(ids)
    L = ["# Impact of the pool's non-exact area-proportionality (exploratory; auto-generated by `scripts/data/pool_weight_impact.py`)", "",
         "## 1. Reference Cp statistics: full mesh vs pool (12 cars)", "",
         "Area-weighted second moment E[Cp^2] (the denominator of rel L2 is its pool counterpart) over all mesh vertices, versus the plain mean over the pool and the IPW estimate.", "",
         f"Plain pool mean: mean error {v['naive err %'].mean():+.2f}%, max |error| {v['naive err %'].abs().max():.2f}%. IPW: mean error {v['IPW err %'].mean():+.2f}%, max |error| {v['IPW err %'].abs().max():.2f}%. "
         f"Mean Cp (exact / plain / IPW, averages over cars): {v['exact E[cp]'].mean():+.4f} / {v['naive E[cp]'].mean():+.4f} / {v['IPW E[cp]'].mean():+.4f}.", "", v.round(4).to_string(index=False), "",
         "## 2. Per-car rel L2 with plain versus IPW weights (E2 test cars)", ""]
    rows, pair = [], []
    for fold, held in FOLDS.items():
        ids_f = list(pd.read_csv(RES / f"{fold}_M2_R2_s0" / "test_per_car.csv").id)
        pools = [np.load(ROOT / "data" / "cache" / i / "pool.npz") for i in ids_f]
        refs = [np.clip(p["cp"].astype(np.float64), *CLIP) for p in pools]
        ws = [weights(p["area"].astype(np.float64), i) for p, i in zip(pools, ids_f)]
        per = {}
        for model, rdir, seeds in (("M2", "M2_R2", (0, 1, 2)), ("B2", "B2_R1", (0,))):
            preds = [np.load(RES / f"{fold}_{rdir}_s{s}" / "test_pred_fp16.npy", mmap_mode="r") for s in seeds]
            u = np.array([[rel_l2(np.asarray(p[j], np.float64), refs[j], np.ones_like(refs[j])) for j in range(len(ids_f))] for p in preds]).mean(0)
            w = np.array([[rel_l2(np.asarray(p[j], np.float64), refs[j], ws[j]) for j in range(len(ids_f))] for p in preds]).mean(0)
            per[model] = (u, w)
            rows.append({"fold": fold, "model": model, "plain mean rel L2": f"{u.mean():.4f}", "IPW rel L2": f"{w.mean():.4f}", "relative change %": f"{100 * (w.mean() / u.mean() - 1):+.2f}",
                         "per-car Spearman": f"{spearmanr(u, w)[0]:.4f}", "max |per-car change| %": f"{100 * np.abs(w / u - 1).max():.2f}"})
        for tag, k in (("plain", 0), ("IPW", 1)):
            d = per["M2"][k] - per["B2"][k]
            m, lo, hi = bootstrap_ci(d)
            pair.append({"fold": fold, "weights": tag, "mean diff (M2 - B2)": f"{m:+.4f}", "95% CI": f"[{lo:+.4f}; {hi:+.4f}]", "cars M2 better": f"{(d < 0).mean() * 100:.0f}%"})
        print(rows[-2], rows[-1], flush=True)
    cols = list(rows[0])
    L += ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)] + ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows]
    cols = list(pair[0])
    L += ["", "## 3. Paired M2 - B2 under both weightings", "", "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)] + ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in pair]
    L += ["", "Not recomputable from stored data: B0/B1 (only per-car metrics were saved) and M2 on E1 (predictions were not saved when E1 ran), hence D and the confirmatory M2 vs B1 test are not re-evaluated here.", ""]
    Path(a.out).write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
