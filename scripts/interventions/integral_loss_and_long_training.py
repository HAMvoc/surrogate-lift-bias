"""Prereg addendum 3 (exploratory): A) integral loss, B) active calibration selection, C) B2 300 epochs. Writes reports/addendum3.md.
Usage: python scripts/interventions/integral_loss_and_long_training.py"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT))
from scripts.diagnosis.region_errors import md  # noqa: E402
from scripts.diagnosis.pressure_coefficients import CLIP, boot, cdp  # noqa: E402
from scripts.diagnosis.physics_plots import cl  # noqa: E402

RES, CACHE = ROOT / "results", ROOT / "data" / "cache"
POOLS = {}


def pool(i):
    if i not in POOLS:
        p = np.load(CACHE / i / "pool.npz")
        ref = np.clip(p["cp"].astype(np.float64), *CLIP)
        one = np.ones(len(ref))
        POOLS[i] = (p, ref, 1000 * cdp(ref, p["normal"][:, 0], p["area"], i), 1000 * cl(ref, p["normal"][:, 2], p["area"], i, one))
    return POOLS[i]


def evaluate(ids, run):
    """Per-car errors of `run` restricted to `ids` (order of the run's test_per_car.csv is used to find the rows)."""
    d = RES / run
    t = pd.read_csv(d / "test_per_car.csv")
    pr = np.load(d / "test_pred_fp16.npy", mmap_mode="r")
    pos = {i: n for n, i in enumerate(t.id)}
    e_d, e_l = [], []
    for i in ids:
        p, ref, rd, rl = pool(i)
        c = np.asarray(pr[pos[i]], np.float64)
        e_d.append(1000 * cdp(c, p["normal"][:, 0], p["area"], i) - rd)
        e_l.append(1000 * cl(c, p["normal"][:, 2], p["area"], i, np.ones(len(c))) - rl)
    e_d, e_l = np.array(e_d), np.array(e_l)
    lo, hi = boot(e_l, np.mean)
    val = pd.read_csv(d / "val_per_car.csv").rel_l2.mean()
    return {"rel": t.set_index("id").loc[list(ids)].rel_l2.mean(), "bias": float(e_l.mean()), "ci": (lo, hi), "mae": float(np.abs(e_l).mean()), "d_bias": float(e_d.mean()), "d_mae": float(np.abs(e_d).mean()), "val": val}


def row(label, r, base):
    return {"config": label, "rel L2": f"{r['rel']:.4f}", "C_L,p bias [CI 95%]": f"{r['bias']:+.1f} [{r['ci'][0]:+.1f}; {r['ci'][1]:+.1f}]", "C_L,p MAE": f"{r['mae']:.1f}",
            "bias vs k=0": f"{100 * r['bias'] / base['bias']:.0f}%", "C_D,p bias": f"{r['d_bias']:+.2f}", "C_D,p MAE": f"{r['d_mae']:.2f}", "val": f"{r['val']:.4f}", "val change": f"{r['val'] - base['val']:+.4f}"}


def main():
    text = ["# Addendum 3 results (exploratory; auto-generated by `scripts/interventions/integral_loss_and_long_training.py`)", ""]
    have = lambda n: (RES / n / "test_pred_fp16.npy").exists()
    ids225 = list(pd.read_csv(RES / "E2A_M2_R2_s0_cal5" / "test_per_car.csv").id)
    # A) integral loss
    if have("E2A_M2_R2_s0_ap100") or have("E2A_M2_R2_s0_ap1000"):
        base = evaluate(ids225, "E2A_M2_R2_s0")
        rows = [row("k=0 (no integral loss)", base, base)] + [row(f"lam={l}", evaluate(ids225, f"E2A_M2_R2_s0_ap{l}"), base) for l in (100, 1000) if have(f"E2A_M2_R2_s0_ap{l}")]
        ok = [abs(float(r["bias vs k=0"].rstrip("%"))) for r in rows[1:] if float(r["val change"]) <= 0.005]  # registered: val (F/N cars) must not worsen by more than 0.005
        best = min(ok, default=None)
        verdict = "failure (no run keeps val within +0.005 of k=0; unconstrained best bias is " + f"{min(abs(float(r['bias vs k=0'].rstrip('%'))) for r in rows[1:]):.0f}% of k=0)" if best is None else "practical success (<=50%)" if best <= 50 else "partial (50-75% remains)" if best <= 75 else "failure (>75% of the k=0 bias remains)"
        text += ["## A. Integral loss, zero-shot, E2A (225 Estateback cars of addendum 1)", "", md(rows), "", f"Verdict by the registered rule: **{verdict}**. Registered expectation: failure.", ""]
    # B) active selection on the 125-car test T
    if have("E2A_M2_R2_s0_kc5"):
        t125 = list(pd.read_csv(RES / "E2A_M2_R2_s0_kc5" / "test_per_car.csv").id)
        base = evaluate(t125, "E2A_M2_R2_s0")
        text += ["## B. Active calibration selection (test T = 125 Estateback cars)", "", md([row("k=0", base, base)]), ""]
        out, rand = [], {5: [], 10: []}
        spec = [("random A (pool prefix)", "E2A_M2_R2_s0_cal{k}", "rand"), ("random B", "E2A_M2_R2_s0_rb{k}", "rand"), ("random C", "E2A_M2_R2_s0_rc{k}", "rand"),
                ("k-center", "E2A_M2_R2_s0_kc{k}", "act"), ("novel vs train", "E2A_M2_R2_s0_nv{k}", "act")]
        res = {}
        for k in (5, 10):
            rows = []
            for lab, pat, kind in spec:
                n = pat.format(k=k)
                if not have(n):
                    continue
                r = evaluate(t125, n)
                res[(lab, k)] = r
                rows.append(row(f"{lab}, k={k}", r, base))
                if kind == "rand":
                    rand[k].append(abs(r["bias"]))
            text += [md(rows), ""]
        text += ["Rule: an active strategy beats random if at both k=5 and k=10 its |bias| is below the mean of the random draws by at least max(20 counts, 1 SD of the draws) and val does not worsen by more than 0.005.", ""]
        v = []
        for lab in ("k-center", "novel vs train"):
            ok, parts = True, []
            for k in (5, 10):
                if (lab, k) not in res or len(rand[k]) < 2:
                    ok = False
                    continue
                m, sd = np.mean(rand[k]), np.std(rand[k], ddof=1)
                r = res[(lab, k)]
                gain = m - abs(r["bias"])
                good = gain >= max(20, sd) and r["val"] - base["val"] <= 0.005
                ok &= good
                parts.append(f"k={k}: |bias| {abs(r['bias']):.1f} vs random mean {m:.1f} (SD {sd:.1f}), gain {gain:+.1f} -> {'pass' if good else 'no'}")
            v.append(f"- {lab}: {'**better than random**' if ok else '**not better than random**'} ({'; '.join(parts)})")
        text += v + [""]
    # C) B2 300 epochs
    rows = []
    for f in ("E2A", "E2B", "E2C"):
        if not have(f"{f}_B2_R1_s0_ep300"):
            continue
        ids = list(pd.read_csv(RES / f"{f}_M2_R2_s0" / "test_per_car.csv").id)
        for lab, run in (("M2 R2 150 ep", f"{f}_M2_R2_s0"), ("B2 150 ep", f"{f}_B2_R1_s0"), ("B2 300 ep", f"{f}_B2_R1_s0_ep300")):
            r = evaluate(ids, run)
            rows.append({"fold": f, "model": lab, "rel L2": f"{r['rel']:.4f}", "C_L,p bias": f"{r['bias']:+.1f}", "C_D,p bias": f"{r['d_bias']:+.2f}", "C_D,p MAE": f"{r['d_mae']:.2f}"})
    if rows:
        text += ["## C. B2 300 epochs vs 150 epochs and M2 (all 250 test cars of each fold)", "", md(rows), ""]
    (ROOT / "reports" / "addendum3.md").write_text(chr(10).join(text), encoding="utf-8")


if __name__ == "__main__":
    main()
