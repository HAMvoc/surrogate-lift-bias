"""Prereg addendum 4 (exploratory): A) seeds 0-2 for the Occupancy, noXYZ and R3 ablations on E2A, B) 5-stage encoder at R3. Writes reports/addendum4.md.
Usage: python scripts/interventions/ablation_seeds.py"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT))
from scripts.diagnosis.region_errors import accumulate, md  # noqa: E402
from scripts.diagnosis.pressure_coefficients import CLIP  # noqa: E402
from src.evaluation.regions import load_regions  # noqa: E402

RES = ROOT / "results"
CONF = [("M2 R2 (reference)", "E2A_M2_R2_s{s}"), ("Occupancy (M2OCC R2)", "E2A_M2OCC_R2_s{s}"), ("no xyz (M2NOXYZ R2)", "E2A_M2NOXYZ_R2_s{s}"), ("M2 R3 (4 stages)", "E2A_M2_R3_s{s}")]


def rel(name):
    return pd.read_csv(RES / name / "test_per_car.csv").rel_l2.mean()


def main():
    stats = {}
    rows = []
    for lab, pat in CONF:
        v = [rel(pat.format(s=s)) for s in (0, 1, 2)]
        stats[lab] = (np.mean(v), np.std(v, ddof=1))
        rows.append({"config": lab, "seed 0": f"{v[0]:.4f}", "seed 1": f"{v[1]:.4f}", "seed 2": f"{v[2]:.4f}", "mean": f"{np.mean(v):.4f}", "SD": f"{np.std(v, ddof=1):.4f}"})
    ref = stats["M2 R2 (reference)"]
    out = []
    for lab in list(stats)[1:]:
        d = stats[lab][0] - ref[0]
        thr = 2 * max(ref[1], stats[lab][1])
        out.append({"ablation": lab, "mean difference vs M2 R2": f"{d:+.4f}", "2 x larger SD": f"{thr:.4f}", "distinguishable from seed noise": abs(d) > thr})
    text = ["# Addendum 4 results (exploratory; auto-generated by `scripts/interventions/ablation_seeds.py`)", "",
            "## A. Ablations with three seeds (E2A, rel L2 on the 250 Estateback test cars)", "", md(rows), "", md(out), ""]
    # B) 5-stage R3
    s5 = rel("E2A_M2S5_R3_s0")
    r3m, r3sd = stats["M2 R3 (4 stages)"]
    cfg, names = load_regions()
    ids = list(pd.read_csv(RES / "E2A_M2_R2_s0" / "test_per_car.csv").id)
    reg = {}
    for lab, run in (("M2 R2 s0", "E2A_M2_R2_s0"), ("M2 R3 s0 (4 stages)", "E2A_M2_R3_s0"), ("M2S5 R3 s0 (5 stages)", "E2A_M2S5_R3_s0")):
        cnt, sae, sse, ref2, _ = accumulate(ids, [RES / run], cfg, len(names), CLIP)
        ix = [names.index(n) for n in ("rear_window", "rear_face", "tail")]
        mg = lambda x: x[:, ix].sum(1)
        reg[lab] = {"roof MAE": np.nanmean(sae[:, names.index("roof")] / cnt[:, names.index("roof")]), "rear_closure MAE": np.nanmean(mg(sae) / mg(cnt)), "wheel MAE": np.nanmean(sae[:, names.index("wheel")] / cnt[:, names.index("wheel")])}
    rrows = [{"run": k, **{m: f"{x:.4f}" for m, x in v.items()}} for k, v in reg.items()]
    better = (r3m - s5) > r3sd
    roof_ok = reg["M2S5 R3 s0 (5 stages)"]["roof MAE"] <= reg["M2 R2 s0"]["roof MAE"] and reg["M2S5 R3 s0 (5 stages)"]["rear_closure MAE"] <= reg["M2 R2 s0"]["rear_closure MAE"]
    verdict = "supported" if better and roof_ok else "not supported"
    text += ["## B. R3 with a 5-stage encoder (E2A, seed 0; 7.18M vs 4.95M parameters, not controlled)", "",
             f"rel L2: M2S5 R3 seed 0 = {s5:.4f}; M2 R3 4-stage mean over 3 seeds = {r3m:.4f} (SD {r3sd:.4f}); M2 R2 seed 0 = {rel('E2A_M2_R2_s0'):.4f}. Better than the 4-stage R3 mean by more than its SD: {better}. Roof and rear-closure MAE not above M2 R2's: {roof_ok}.", "",
             md(rrows), "", f"Verdict by the registered rule (receptive-field hypothesis for R3): **{verdict}**.", ""]
    (ROOT / "reports" / "addendum4.md").write_text(chr(10).join(text), encoding="utf-8")


if __name__ == "__main__":
    main()
