"""Data-scaling curve (exploratory, single seed): M2 R2 test rel L2 vs number of train cars on E1 and E2A (held out Estateback).
Subsets are category-stratified (seed 0); epochs scaled to keep the number of optimizer steps. The full-size point is the seed-0 run of the main experiment.
Usage: python scripts/interventions/data_scaling.py [--out reports/scaling_curve.md]"""
import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from scripts.diagnosis.pressure_coefficients import CLIP, cdp  # noqa: E402
from scripts.diagnosis.physics_plots import cl  # noqa: E402

RES = ROOT / "results"
SETS = {"E1": (600, (150, 300, 450)), "E2A": (450, (100, 150, 300))}  # split: (full size, subset sizes)


def ci(x, B=1000, seed=0):
    rng = np.random.default_rng(seed)
    m = [x[rng.integers(0, len(x), len(x))].mean() for _ in range(B)]
    return np.percentile(m, 2.5), np.percentile(m, 97.5)


def physics_vs_n():
    """E2A (held out Estateback): C_D,p and C_L,p errors and the degradation D versus the number of train cars (seed 0, saved per-point predictions)."""
    ids = list(pd.read_csv(RES / "E2A_M2_R2_s0" / "test_per_car.csv").id)
    pools = [np.load(ROOT / "data" / "cache" / i / "pool.npz") for i in ids]
    ref = [np.clip(p["cp"].astype(np.float64), *CLIP) for p in pools]
    f_d = lambda j, c: 1000 * cdp(c, pools[j]["normal"][:, 0], pools[j]["area"], ids[j])
    f_l = lambda j, c: 1000 * cl(c, pools[j]["normal"][:, 2], pools[j]["area"], ids[j], np.ones(len(c)))
    r_d, r_l = np.array([f_d(j, ref[j]) for j in range(len(ids))]), np.array([f_l(j, ref[j]) for j in range(len(ids))])
    rows = []
    for n in (*SETS["E2A"][1], SETS["E2A"][0]):
        d = RES / (f"E2A_M2_R2_s0_n{n}" if n < SETS["E2A"][0] else "E2A_M2_R2_s0")
        pr = np.load(d / "test_pred_fp16.npy", mmap_mode="r")
        e_d = np.array([f_d(j, np.asarray(pr[j], np.float64)) for j in range(len(ids))]) - r_d
        e_l = np.array([f_l(j, np.asarray(pr[j], np.float64)) for j in range(len(ids))]) - r_l
        e1 = RES / (f"E1_M2_R2_s0_n{n}" if n < 600 else "E1_M2_R2_s0")
        base = pd.read_csv(e1 / "test_per_car.csv") if e1.exists() else None
        base = None if base is None else base[base.id.str[0] == "E"].rel_l2.mean()  # in-distribution error on the same Estateback cars, same N (E1 train size N)
        rel = pd.read_csv(d / "test_per_car.csv").rel_l2.mean()
        rows.append({"train cars (E2A)": n, "rel L2": f"{rel:.4f}", "D (vs E1 Estateback, same N)": f"{rel / base:.3f}" if base and n in (150, 300, 450) else "-",
                     "C_D,p MAE (counts)": f"{np.abs(e_d).mean():.2f}", "C_D,p bias": f"{e_d.mean():+.2f}", "C_L,p MAE (counts)": f"{np.abs(e_l).mean():.2f}", "C_L,p bias": f"{e_l.mean():+.2f}",
                     "C_L,p CFD sd across cars": f"{r_l.std(ddof=1):.1f}"})
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "reports" / "scaling_curve.md"))
    a = ap.parse_args()
    rows, fig, ax = [], *plt.subplots(1, 2, figsize=(10, 4))
    for k, (sp, (full, ns)) in enumerate(SETS.items()):
        pts = [(n, pd.read_csv(RES / f"{sp}_M2_R2_s0_n{n}" / "test_per_car.csv").rel_l2.to_numpy()) for n in ns]
        pts.append((full, pd.read_csv(RES / f"{sp}_M2_R2_s0" / "test_per_car.csv").rel_l2.to_numpy()))
        N, mean = np.array([p[0] for p in pts]), np.array([p[1].mean() for p in pts])
        b = -np.polyfit(np.log(N), np.log(mean), 1)[0]  # descriptive power-law exponent, err ~ N^-b
        for (n, x), mu in zip(pts, mean):
            lo, hi = ci(x)
            rows.append({"split": sp, "train cars": n, "test cars": len(x), "rel L2 [CI 95% over cars]": f"{mu:.4f} [{lo:.4f}; {hi:.4f}]", "vs full": f"{100 * (mu / mean[-1] - 1):+.1f}%"})
        lo_hi = np.array([ci(x) for _, x in pts]).T
        ax[k].errorbar(N, mean, yerr=[mean - lo_hi[0], lo_hi[1] - mean], marker="o", capsize=3)
        ax[k].set(xscale="log", yscale="log", xlabel="train cars", ylabel="test rel L2", title=f"{sp} (log-log slope {-b:.2f})")
        ax[k].set_xticks(N, [str(n) for n in N])
        ax[k].grid(alpha=0.3, which="both")
    fig.tight_layout()
    fig.savefig(ROOT / "reports" / "scaling_curve.png", dpi=100)
    cols = list(rows[0])
    text = ["# Data-scaling curve (exploratory; auto-generated by `scripts/interventions/data_scaling.py`)", "",
            "M2 R2, lr 3e-3, seed 0, category-stratified train subsets, epochs scaled to keep the optimizer-step count. Single seed (noise 0.002-0.006) and one subset per size: differences below that are not interpreted. "
            "CI over test cars only; it does not include subset or seed variability.", "", "![curve](scaling_curve.png)", "",
            "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)] + ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows] + [""]
    phys = physics_vs_n()
    pc = list(phys[0])
    text += ["", "## Physics errors versus N on E2A (held out Estateback; seed 0, 250 test cars; same estimators as `reports/cdp_analysis.md` and `reports/physics_plots.md`)", "",
             "D uses the E1 Estateback test cars (25) of the E1 run with the same number of train cars; E1 and E2A subsets differ, so D(N) is only available at N = 150, 300, 450.", "",
             "| " + " | ".join(pc) + " |", "|" + "---|" * len(pc)] + ["| " + " | ".join(str(r[c]) for c in pc) + " |" for r in phys] + [""]
    Path(a.out).write_text("\n".join(text), encoding="utf-8")
    print("\n".join(text))


if __name__ == "__main__":
    main()
