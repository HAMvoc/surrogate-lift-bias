"""Sensitivity of rel L2 and of the degradation ratio D to the Cp clipping range of the target (exploratory; prereg promised this check).
Predictions are the saved per-point test predictions (trained on Cp clipped to [-10, 1]); only the target used for evaluation changes.
Model run: first available seed with saved predictions (M2: seed 0 on E2, seed 2 on E1 because seeds 0-1 of E1 have no saved predictions).
Usage: python scripts/diagnosis/clip_sensitivity.py"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT))
from scripts.diagnosis.region_errors import md  # noqa: E402
from scripts.diagnosis.pressure_coefficients import MODELS, run_dirs  # noqa: E402

CACHE = ROOT / "data" / "cache"
CLIPS = {"[-8, 1]": (-8, 1), "[-10, 1] (used)": (-10, 1), "[-15, 1]": (-15, 1), "raw": (-np.inf, np.inf)}
HELD = {"E2A": "E", "E2B": "N", "E2C": "F"}


def rel_l2(fold, model, lo_hi):
    d = run_dirs(fold, model[1], model[2], model[3])[0]
    ids = list(pd.read_csv(d / "test_per_car.csv").id)
    pr = np.load(d / "test_pred_fp16.npy", mmap_mode="r")
    out = []
    for n, i in enumerate(ids):
        cp = np.clip(np.load(CACHE / i / "pool.npz")["cp"].astype(np.float64), *lo_hi)
        p = np.asarray(pr[n], np.float64)
        out.append(np.linalg.norm(p - cp) / np.linalg.norm(cp))
    return pd.Series(out, index=ids)


def main():
    rows, outside = [], None
    for cname, c in CLIPS.items():
        for m in MODELS:
            e1 = rel_l2("E1", m, c)
            row = {"clip": cname, "model": m[0], "E1": f"{e1.mean():.4f}"}
            for f, s in HELD.items():
                e = rel_l2(f, m, c)
                row[f] = f"{e.mean():.4f}"
                row[f"D {f}"] = f"{e.mean() / e1[[i for i in e1.index if i[0] == s]].mean():.3f}"
            rows.append(row)
            print(row, flush=True)
    ids = list(pd.read_csv(run_dirs("E2A", "M2_R2", (0,), "")[0] / "test_per_car.csv").id)
    raw = np.concatenate([np.load(CACHE / i / "pool.npz")["cp"].astype(np.float64) for i in ids])
    frac = {k: float(np.mean((raw < lo) | (raw > hi))) for k, (lo, hi) in CLIPS.items() if np.isfinite(lo)}
    order = {c: " < ".join(r["model"] for r in sorted([r for r in rows if r["clip"] == c], key=lambda r: float(r["E2A"]))) for c in CLIPS}
    text = ["# Sensitivity to the Cp clipping range (exploratory; auto-generated by `scripts/diagnosis/clip_sensitivity.py`)", "",
            "Predictions are unchanged (trained on Cp clipped to [-10, 1]); the evaluation target is clipped to each range. Per-car rel L2 on the 100k-point pool, mean over test cars. "
            "D = held-out-style rel L2 / E1 rel L2 on the 25 E1 test cars of the same style. M2: seed 0 on E2, seed 2 on E1 (only seed with saved predictions); B1/B2/B3: seed 0.", "",
            md(rows), "", "Ranking on E2A (best to worst) per clip: " + "; ".join(f"{k}: {v}" for k, v in order.items()) + ".", "",
            "Share of E2A test points outside the range: " + ", ".join(f"{k} {100 * v:.3f}%" for k, v in frac.items()) + ".", ""]
    (ROOT / "reports" / "clip_sensitivity.md").write_text(chr(10).join(text), encoding="utf-8")


if __name__ == "__main__":
    main()
