"""Pressure-drag diagnostic (spec 10.5, exploratory): C_D,p = -(1/A_ref) * sum_i Cp_i A_i (n_i . e), e = +x, from the 100k-point pool.
The pool is area-proportional, so the sum is estimated with inverse-inclusion-probability weights (the pool is not exactly area-proportional). The reference uses the same formula on the CFD labels
(clipped Cp, the model's target); it is NOT compared with total Cd (no friction drag). Reports MAE in drag counts (1 count = 0.001), signed bias and the
Spearman rank correlation within each held-out body style. First validates the pool estimator against the full-mesh vertex integral on a few cars.
Usage: python scripts/diagnosis/pressure_coefficients.py [--out reports/cdp_analysis.md]"""
import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT))
from src.data.grid import load_cfg  # noqa: E402

CFG = load_cfg()
CLIP = tuple(CFG["target"]["cp_clip"])
GEO = pd.read_csv(ROOT / "data" / "manifests" / "car_geometry.csv").set_index("sample_id")
CD = pd.read_csv(ROOT / "data" / "raw" / CFG["source"]["cd_csv"]).set_index("ID")["Drag_Value"]
RES = ROOT / "results"
FOLDS = {"E2A": "Estateback", "E2B": "Notchback", "E2C": "Fastback"}
B = 1000
MODELS = (("M2", "M2_R2", (0, 1, 2), ""), ("B1", "B1_R1", (0,), ""), ("B2", "B2_R1", (0,), ""), ("B3", "B3_R1", (0,), "_lr3e-3"))  # (name, run dir stem, seeds, dir suffix)


def run_dirs(fold, stem, seeds, suf):
    """Result dirs of one model on one fold that have saved per-point test predictions."""
    return [d for d in (RES / f"{fold}_{stem}_s{s}{suf}" for s in seeds) if (d / "test_pred_fp16.npy").exists()]


def pool_weights(area, sid):
    """Inverse inclusion probability times vertex area, with pi = 1 - exp(-lambda * area) (see scripts/data/car_geometry.py): the pool is not exactly area-proportional."""
    return area / (1 - np.exp(-GEO.at[sid, "incl_rate_per_m2"] * area))


def cdp(cp, nx, area, sid, naive=False):
    """C_D,p (not yet in counts) from pool values: ratio estimator A_total * sum(w cp nx) / sum(w), w = va / pi (naive: plain mean, i.e. assumes exact area-proportional sampling)."""
    w = np.ones_like(cp) if naive else pool_weights(np.asarray(area, np.float64), sid)
    return -(GEO.at[sid, "area_total_m2"] / GEO.at[sid, "frontal_area_m2"]) * float((w * cp * nx).sum() / w.sum())


def boot(x, f, seed=0):
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(x), (B, len(x)))
    v = np.array([f(x[i]) for i in idx])
    return float(np.percentile(v, 2.5)), float(np.percentile(v, 97.5))


def validate(ids):
    """Pool estimator vs the exact vertex integral over the full surface mesh (same normals/areas as the preprocess)."""
    import pyvista as pv
    from scripts.data.preprocess import vertex_normals_and_areas
    rows = []
    for sid in ids:
        m = pv.read(ROOT / "data" / "raw" / CFG["source"]["vtk_dir"] / f"{sid}.vtk")
        cp = np.clip(np.asarray(m.point_data["p"], np.float64) / (0.5 * CFG["cp"]["u_inf"] ** 2), *CLIP)
        nrm, va = vertex_normals_and_areas(m)
        exact = -float((cp * va.astype(np.float64) * nrm[:, 0]).sum()) / GEO.at[sid, "frontal_area_m2"]
        pool = np.load(ROOT / "data" / "cache" / sid / "pool.npz")
        pc, pn, pa = np.clip(pool["cp"].astype(np.float64), *CLIP), pool["normal"][:, 0], pool["area"]
        rows.append((sid, 1000 * exact, 1000 * cdp(pc, pn, pa, sid), 1000 * cdp(pc, pn, pa, sid, naive=True), float(va.sum()), GEO.at[sid, "area_total_m2"], 1000 * CD[sid]))
    return pd.DataFrame(rows, columns=["id", "exact counts", "pool IPW counts", "pool naive counts", "vertex-area sum m2", "cell-area sum m2", "total Cd counts"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "reports" / "cdp_analysis.md"))
    a = ap.parse_args()
    L = ["# Pressure-drag diagnostic C_D,p (exploratory; auto-generated by `scripts/diagnosis/pressure_coefficients.py`)", "",
         "C_D,p = -(1/A_ref) sum Cp A (n . e) with e = +x, from the CFD labels (clipped Cp) and from model predictions at the same 100k pool points. "
         "A_total from the CFD surface mesh, A_ref (frontal area) from the cached R3 occupancy (about 1% below a mesh rasterisation, same scale for reference and prediction). "
         "Counts: 1 count = 0.001. C_D,p is a pressure-only diagnostic, not a drag coefficient (no friction drag), and is not compared with total Cd.", ""]
    sample = [i for i in GEO.index[:: len(GEO) // 8]][:8]
    v = validate(sample)
    err, naive = v["pool IPW counts"] - v["exact counts"], v["pool naive counts"] - v["exact counts"]
    L += ["## Pool estimator vs full-mesh integral (8 cars)", "",
          f"Error relative to the exact integral over all mesh vertices. Inverse-probability weighted pool estimate (used below): mean {err.mean():+.2f} counts, max |error| {err.abs().max():.2f} counts "
          f"({100 * (err.abs() / v['exact counts']).max():.2f}% of C_D,p). Naive pool mean (assumes exact area-proportional sampling): mean {naive.mean():+.2f}, max |error| {naive.abs().max():.2f} counts. Pressure share: C_D,p / total Cd = {(v['exact counts'] / v['total Cd counts']).mean():.2f} on these cars. "
          f"Vertex-area sum vs triangle-area sum differ by at most {(100 * (v['vertex-area sum m2'] / v['cell-area sum m2'] - 1)).abs().max():.2f}%.", "",
          v.round(2).to_markdown(index=False) if hasattr(v, "to_markdown") else v.round(2).to_string(index=False), ""]
    pool_noise = float(err.abs().max())
    rows = []
    for fold, held in FOLDS.items():
        csv_ids = list(pd.read_csv(RES / f"{fold}_M2_R2_s0" / "test_per_car.csv").id)
        pools = [np.load(ROOT / "data" / "cache" / i / "pool.npz") for i in csv_ids]
        nx = np.stack([p["normal"][:, 0] for p in pools])
        ar = np.stack([p["area"] for p in pools])
        ref_cp = np.stack([np.clip(p["cp"].astype(np.float64), *CLIP) for p in pools])
        ref = np.array([1000 * cdp(ref_cp[j], nx[j], ar[j], i) for j, i in enumerate(csv_ids)])
        for model, rdir, seeds, suf in MODELS:
            runs = run_dirs(fold, rdir, seeds, suf)
            if not runs:
                continue
            preds = [np.load(r / "test_pred_fp16.npy", mmap_mode="r") for r in runs]
            est = np.array([[1000 * cdp(np.asarray(p[j], np.float64), nx[j], ar[j], i) for j, i in enumerate(csv_ids)] for p in preds])  # (seeds, cars)
            abs_err = np.abs(est - ref).mean(0)  # per car, averaged over seeds
            bias = (est - ref).mean()
            rho_of = lambda ii: float(np.mean([spearmanr(e[ii], ref[ii])[0] for e in est]))  # per seed, then averaged: no ensembling of the 3 M2 seeds
            rho = rho_of(np.arange(len(ref)))
            lo, hi = boot(abs_err, np.mean)
            rlo, rhi = boot(np.arange(len(ref)), rho_of)
            rows.append({"fold": fold, "held out": held, "model": model, "n cars": len(ref), "C_D,p ref mean [min, max] (counts)": f"{ref.mean():.1f} [{ref.min():.1f}, {ref.max():.1f}]",
                         "ref sd (counts)": f"{ref.std(ddof=1):.1f}", "MAE (counts) [CI 95%]": f"{abs_err.mean():.2f} [{lo:.2f}; {hi:.2f}]", "signed bias (counts)": f"{bias:+.2f}",
                         "Spearman rho [CI 95%]": f"{rho:.3f} [{rlo:.3f}; {rhi:.3f}]", "seeds": len(runs)})
            print(rows[-1], flush=True)
    cols = list(rows[0])
    L += ["## Per held-out body style (test cars of E2A / E2B / E2C)", "",
          "MAE = mean over cars of the seed-averaged absolute error; bias = mean signed error; Spearman per seed versus the CFD value within the fold, then averaged over seeds (no ensembling of seeds) "
          "(= within one body style); CI by bootstrap over cars (B = 1000).", "",
          "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)] + ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows]
    L += ["", f"Reference values from the pool differ from the exact full-mesh integral by at most {pool_noise:.2f} counts on the 8 validation cars (mean {err.mean():+.2f}), "
          "i.e. a few counts of noise in the absolute reference. The model error (prediction minus reference) is computed at the same points with the same weights, "
          "so it does not contain that sampling noise; it measures the model error on the pool-weighted integral.", ""]
    Path(a.out).write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
