"""Exploratory (DB-4): (1) error by wheel configuration (WW open / WWS smooth, from the car id) within each body style;
(2) signed region bias of every model on each held-out fold (pred - CFD, clipped Cp, mean over cars with bootstrap CI): roof, rear window, rear face (base pressure), wheels;
(3) centerline Cp (|y| < 3 cm, upper surface) mean +- SD over ALL test cars of each fold: CFD vs models.
Per-seed errors are averaged (no ensembling of the 3 M2 seeds); the centerline uses seed 0 of every model.
Usage: python scripts/diagnosis/wheel_and_bias.py"""
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT))
from scripts.diagnosis.region_errors import boot_ci, md  # noqa: E402
from scripts.diagnosis.pressure_coefficients import CLIP, FOLDS, MODELS, RES, run_dirs  # noqa: E402
from scripts.diagnosis.physics_plots import BAND, L_REF, STEP, profile  # noqa: E402
from src.evaluation.regions import assign_regions, load_regions  # noqa: E402

CACHE = ROOT / "data" / "cache"
KEEP = ("wheel", "roof", "rear_window", "rear_face", "tail", "hood")
COL = {"CFD": "k", "M2": "tab:red", "B1": "tab:green", "B2": "tab:blue", "B3": "tab:orange"}
wheel_cfg = lambda i: "WWS" if "_WWS_" in i else "WW"


def wheel_table():
    rows = []
    for sp in ("E1", *FOLDS):
        for name, stem, seeds, suf in MODELS:
            d = pd.concat([pd.read_csv(RES / f"{sp}_{stem}_s{s}{suf}" / "test_per_car.csv").assign(seed=s) for s in seeds if (RES / f"{sp}_{stem}_s{s}{suf}" / "test_per_car.csv").exists()])
            d = d.groupby("id", as_index=False).rel_l2.mean()  # mean over seeds per car
            d["style"], d["cfg"] = d.id.str[0], d.id.map(wheel_cfg)
            for (style, cfg), g in d.groupby(["style", "cfg"]):
                rows.append({"split": sp, "model": name, "body style": style, "wheels": cfg, "n cars": len(g), "rel L2": f"{g.rel_l2.mean():.4f}"})
    return rows


def bias_and_centerline(cfg, names):
    keep = [names.index(k) for k in KEEP]
    rows, prof = [], {}
    for fold, held in FOLDS.items():
        ids = list(pd.read_csv(RES / f"{fold}_M2_R2_s0" / "test_per_car.csv").id)
        pools = [np.load(CACHE / i / "pool.npz") for i in ids]
        reg = [assign_regions(p["xyz"], p["normal"], cfg) for p in pools]
        ref = [np.clip(p["cp"].astype(np.float64), *CLIP) for p in pools]
        mask = [(np.abs(p["xyz"][:, 1] * L_REF) < BAND) & (np.abs(p["normal"][:, 1]) < 0.4) & (p["normal"][:, 2] > 0.3) for p in pools]
        curves = {"CFD": np.stack([profile(p["xyz"][:, 0] * L_REF, ref[j], mask[j])[1] for j, p in enumerate(pools)])}
        x = profile(pools[0]["xyz"][:, 0] * L_REF, ref[0], mask[0])[0]
        for model, stem, seeds, suf in MODELS:
            runs = run_dirs(fold, stem, seeds, suf)
            if not runs:
                continue
            preds = [np.load(r / "test_pred_fp16.npy", mmap_mode="r") for r in runs]
            bias = np.full((len(ids), len(keep)), np.nan)
            for j in range(len(ids)):
                for k, r in enumerate(keep):
                    m = reg[j] == r
                    if m.any():
                        bias[j, k] = np.mean([np.mean(np.asarray(p[j], np.float64)[m] - ref[j][m]) for p in preds])
            mu, lo, hi = boot_ci(bias)
            rows.append({"fold": f"{fold} ({held})", "model": model, **{n: f"{mu[k]:+.3f} [{lo[k]:+.3f}; {hi[k]:+.3f}]" for k, n in enumerate(KEEP)}})
            curves[model] = np.stack([profile(pools[j]["xyz"][:, 0] * L_REF, np.asarray(preds[0][j], np.float64), mask[j])[1] for j in range(len(ids))])
        prof[fold] = (x, curves)
    return rows, prof


def main():
    cfg, names = load_regions()
    wt = wheel_table()
    rows, prof = bias_and_centerline(cfg, names)
    fig, ax = plt.subplots(1, 3, figsize=(16, 4.2), sharey=True)
    for a, (fold, (x, curves)) in zip(ax, prof.items()):
        for name, c in curves.items():
            m, sd = np.nanmean(c, 0), np.nanstd(c, 0)
            a.plot(x, m, color=COL[name], lw=2 if name == "CFD" else 1.2, label=name)
            if name in ("CFD", "M2"):
                a.fill_between(x, m - sd, m + sd, color=COL[name], alpha=0.12)
        a.set_title(f"{fold} (held out {FOLDS[fold]}): mean +- SD over {len(curves['CFD'])} cars", fontsize=9)
        a.set_xlabel("x from nose (m)")
        a.grid(alpha=0.3)
    ax[0].set_ylabel("Cp, upper surface, |y| < 3 cm")
    ax[0].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(ROOT / "reports" / "centerline_mean_sd.png", dpi=90)
    text = ["# Wheel configuration, signed region bias and mean centerline (exploratory; auto-generated by `scripts/diagnosis/wheel_and_bias.py`)", "",
            "## 1. Error by wheel configuration (WW = open wheels, WWS = smooth wheels, from the car id)", "",
            "Per-car rel L2 (mean over seeds per car). All 250 Estateback cars are WW, so WWS cannot be tested for that style. Compare WW and WWS within the same body style.", "", md(wt), "",
            "## 2. Signed bias by region on each held-out fold (prediction minus CFD, clipped Cp; mean over cars [bootstrap CI 95%])", "",
            "Positive = prediction less negative / higher pressure than CFD. Roof and rear window bias show the suction error; rear face is the base-pressure error (Cp = -0.2 to -0.3 on the rear face of a squareback).", "", md(rows), "",
            "## 3. Mean centerline Cp over all test cars of each fold", "", "![centerline](centerline_mean_sd.png)", "",
            "Upper-surface profile within 3 cm of the symmetry plane on near-horizontal surfaces (normal |n_y| < 0.4, n_z > 0.3), 5 cm bins, seed 0 of every model. Surfaces facing the flow (nose) or facing rearwards (rear face) are not in this profile; the rear-face base pressure is in table 2.", ""]
    (ROOT / "reports" / "wheel_and_bias.md").write_text("\n".join(text), encoding="utf-8")
    print("\n".join(text[:30]))


if __name__ == "__main__":
    main()
