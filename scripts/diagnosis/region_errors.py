"""Exploratory error analysis on the saved per-point test predictions (spec 10.4, E6):
(1) error by surface region (area share, MAE, rel L2, share of total squared error, enrichment = error share / area share), M2 and B2;
(2) error vs geometric novelty (SDF R1 distance from each test car to its nearest train car), Spearman.
Everything is exploratory. Predictions are the per-seed outputs averaged per car (same convention as the primary metric).
Usage: python scripts/diagnosis/region_errors.py [--out reports/region_analysis.md]"""
import argparse
import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.stats import spearmanr

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT))
from scripts.diagnosis.pressure_coefficients import MODELS, run_dirs  # noqa: E402
from src.data.grid import load_cfg  # noqa: E402
from src.evaluation.regions import assign_regions, load_regions  # noqa: E402

FOLDS = {"E2A": "Estateback", "E2B": "Notchback", "E2C": "Fastback"}
RES, CACHE = ROOT / "results", ROOT / "data" / "cache"
B = 1000


def boot_ci(x, seed=0):
    """Per-car bootstrap CI of the column means of x (cars x regions); NaN entries (car has no points in the region) are skipped."""
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(x), (B, len(x)))
    m = np.nanmean(x[idx], axis=1)
    return np.nanmean(x, axis=0), np.nanpercentile(m, 2.5, axis=0), np.nanpercentile(m, 97.5, axis=0)


def accumulate(ids, runs, cfg, nreg, clip):
    """Per car and region: point count, sum|err|, sum err^2 (averaged over runs/seeds), sum ref^2. Also checks prediction/id alignment."""
    n = len(ids)
    cnt, sae, sse, ref2 = (np.zeros((n, nreg)) for _ in range(4))
    preds = [np.load(d / "test_pred_fp16.npy", mmap_mode="r") for d in runs]
    check = np.zeros(n)
    for j, i in enumerate(ids):
        p = np.load(CACHE / i / "pool.npz")
        ref = np.clip(p["cp"].astype(np.float64), *clip)
        r = assign_regions(p["xyz"], p["normal"], cfg)
        cnt[j] = np.bincount(r, minlength=nreg)
        ref2[j] = np.bincount(r, weights=ref ** 2, minlength=nreg)
        for k, pr in enumerate(preds):
            e = pr[j].astype(np.float64) - ref
            sae[j] += np.bincount(r, weights=np.abs(e), minlength=nreg) / len(preds)
            e2 = np.bincount(r, weights=e * e, minlength=nreg)
            sse[j] += e2 / len(preds)
            if k == 0:
                check[j] = np.sqrt(e2.sum() / ref2[j].sum())
    return cnt, sae, sse, ref2, check


def region_table(cnt, sae, sse, ref2, names):
    area = cnt / cnt.sum(1, keepdims=True)
    share = sse / sse.sum(1, keepdims=True)
    with np.errstate(invalid="ignore", divide="ignore"):
        mae = np.where(cnt > 0, sae / cnt, np.nan)
        rel = np.where(ref2 > 0, np.sqrt(sse / ref2), np.nan)
    a, s, mae_m, rel_m = area.mean(0), boot_ci(share), np.nanmean(mae, 0), np.nanmean(rel, 0)
    rows = [{"region": nm, "area share %": f"{100 * a[k]:.1f}", "MAE": f"{mae_m[k]:.4f}", "rel L2 (region)": f"{rel_m[k]:.3f}",
             "error share % [CI 95%]": f"{100 * s[0][k]:.1f} [{100 * s[1][k]:.1f}; {100 * s[2][k]:.1f}]", "enrichment": f"{s[0][k] / a[k]:.2f}"} for k, nm in enumerate(names)]
    return rows, a, s[0], mae_m


def md(rows):
    cols = list(rows[0])
    return "\n".join(["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)] + ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows]) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "reports" / "region_analysis.md"))
    a = ap.parse_args()
    cfg, names = load_regions()
    clip = tuple(load_cfg()["target"]["cp_clip"])
    nreg = len(names)
    L = ["# Region and novelty analysis (exploratory; auto-generated by `scripts/diagnosis/region_errors.py`)", "",
         f"Regions: `configs/regions.yaml` (rules on per-car normalized coordinates and normals). Error on clipped Cp; per-seed errors averaged; shares are means over cars with per-car bootstrap CI (B = {B}). "
         "Enrichment = error share / area share (above 1 means the region carries more error than its area).", ""]
    summary = {}
    for model, rdir, seeds, suf in MODELS:
        for f, held in FOLDS.items():
            runs = run_dirs(f, rdir, seeds, suf)
            if not runs:
                continue
            csv = pd.read_csv(runs[0] / "test_per_car.csv")
            ids = list(csv.id)
            cnt, sae, sse, ref2, check = accumulate(ids, runs, cfg, nreg, clip)
            assert np.abs(check - csv.rel_l2.to_numpy()).max() < 2e-3, f"{f} {model}: predictions are not aligned with test_per_car.csv"
            rows, area, share, mae = region_table(cnt, sae, sse, ref2, names)
            # the Estateback rear window is almost vertical and mostly falls into rear_face, so the three rear regions are also reported merged (avoids a tiny-area artefact in the enrichment)
            ix = [names.index(n) for n in ("rear_window", "rear_face", "tail")]
            mg = lambda x: x[:, ix].sum(1, keepdims=True)
            a_m, s_m = (mg(cnt) / cnt.sum(1, keepdims=True)).mean(), boot_ci(mg(sse) / sse.sum(1, keepdims=True))
            rows.append({"region": "rear_closure (rear_window+rear_face+tail)", "area share %": f"{100 * a_m:.1f}", "MAE": f"{np.nanmean(mg(sae) / mg(cnt)):.4f}", "rel L2 (region)": f"{np.nanmean(np.sqrt(mg(sse) / mg(ref2))):.3f}",
                         "error share % [CI 95%]": f"{100 * s_m[0][0]:.1f} [{100 * s_m[1][0]:.1f}; {100 * s_m[2][0]:.1f}]", "enrichment": f"{s_m[0][0] / a_m:.2f}"})
            summary[(model, f)] = dict(area=area, share=share, mae=mae, ids=ids, rel=np.sqrt(sse.sum(1) / ref2.sum(1)))
            L += [f"## {model}, {f} (held out {held}, {len(ids)} cars, {len(runs)} seed(s))", "", md(rows)]
    # M2 vs each baseline by region (MAE ratio), exploratory
    for other in ("B1", "B2", "B3"):
        rows = []
        for f in FOLDS:
            if ("M2", f) in summary and (other, f) in summary:
                r = summary[("M2", f)]["mae"] / summary[(other, f)]["mae"]
                rows.append({"fold": f, **{nm: f"{r[k]:.2f}" for k, nm in enumerate(names)}})
        if rows:
            L += [f"## M2 / {other} MAE ratio by region (below 1: M2 better)", "", md(rows)]
    # figure: enrichment and MAE by region and fold (M2)
    fig, ax = plt.subplots(1, 2, figsize=(14, 4.2))
    w = 0.26
    for k, (f, held) in enumerate(FOLDS.items()):
        s = summary.get(("M2", f))
        if s is None:
            continue
        ax[0].bar(np.arange(nreg) + (k - 1) * w, s["share"] / s["area"], w, label=f"{f} ({held})")
        ax[1].bar(np.arange(nreg) + (k - 1) * w, s["mae"], w, label=f"{f} ({held})")
    for a_, t in zip(ax, ("Error enrichment (error share / area share), M2", "MAE by region, M2")):
        a_.set_xticks(range(nreg)); a_.set_xticklabels(names, rotation=40, ha="right"); a_.set_title(t, fontsize=10); a_.legend(fontsize=8)
    ax[0].axhline(1.0, color="k", lw=0.8)
    fig.tight_layout(); fig.savefig(ROOT / "reports" / "region_error.png", dpi=90); plt.close(fig)
    L += ["![region error](region_error.png)", ""]

    # geometric novelty: nearest train car by SDF R1 distance vs per-car error
    z = np.load(ROOT / "data" / "manifests" / "dist_R1.npz", allow_pickle=True)
    pos = {i: k for k, i in enumerate(z["ids"])}
    rows, fig, ax = [], *plt.subplots(1, 1, figsize=(6.5, 4.5))
    allx, ally = [], []
    for model in ("M2", "B1", "B2", "B3"):
        for f, held in FOLDS.items():
            s = summary.get((model, f))
            if s is None:
                continue
            tr = [pos[i] for i in json.loads((ROOT / "data" / "manifests" / "splits" / f"{f}.json").read_text())["train"]]
            for tag, key in (("full-car SDF", "full"), ("front-half SDF", "front")):
                d = np.array([z[key][pos[i], tr].min() for i in s["ids"]])
                rho, p = spearmanr(d, s["rel"])
                rows.append({"model": model, "fold": f, "distance": tag, "Spearman rho": f"{rho:+.3f}", "p": f"{p:.1e}"})
                if model == "M2" and key == "full":
                    ax.scatter(d, s["rel"], s=6, label=f"{f} ({held}), rho={rho:+.2f}")
    ax.set_xlabel("distance to nearest train car (SDF R1, full car)"); ax.set_ylabel("per-car rel L2 (M2)"); ax.legend(fontsize=8)
    fig.tight_layout(); fig.savefig(ROOT / "reports" / "novelty_error.png", dpi=90); plt.close(fig)
    L += ["## Error vs geometric novelty (Spearman between a test car's nearest-train SDF distance and its rel L2)", "", md(rows), "![novelty](novelty_error.png)", ""]
    Path(a.out).write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
