"""Seed-ensemble uncertainty gate (prereg addendum 1, B; exploratory): does the spread of the 3 M2 seeds flag where / for which cars the prediction is wrong?
Per fold E2A/E2B/E2C: sigma = per-point std over seeds 0-2; error = (seed-mean prediction) - CFD on clipped Cp.
Metrics and thresholds (usable if per-car Spearman >= 0.4 AND per-car mean AUROC >= 0.7 in all three folds).
Usage: python scripts/diagnosis/seed_spread_check.py"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import rankdata, spearmanr

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT))
from scripts.diagnosis.region_errors import md  # noqa: E402
from scripts.diagnosis.pressure_coefficients import CLIP, FOLDS, RES, run_dirs  # noqa: E402
from scripts.diagnosis.physics_plots import cl  # noqa: E402
from src.evaluation.regions import assign_regions, load_regions  # noqa: E402

CACHE = ROOT / "data" / "cache"
THR_ERR, GATE_RHO, GATE_AUC = 0.3, 0.4, 0.7


def auroc(score, pos):
    """P(score of a bad point > score of a good point); NaN if one class is empty."""
    n1 = int(pos.sum())
    if n1 == 0 or n1 == len(pos):
        return np.nan
    r = rankdata(score)
    return (r[pos].sum() - n1 * (n1 + 1) / 2) / (n1 * (len(pos) - n1))


def main():
    cfg, names = load_regions()
    rows, reg_rows, cl_rows, verdict = [], [], [], []
    for fold, held in FOLDS.items():
        runs = run_dirs(fold, "M2_R2", (0, 1, 2), "")
        assert len(runs) == 3, f"{fold}: need 3 seeds with saved predictions"
        preds = [np.load(r / "test_pred_fp16.npy", mmap_mode="r") for r in runs]
        ids = list(pd.read_csv(runs[0] / "test_per_car.csv").id)
        sig_car, rel_car, auc, reg_sig, reg_mae, cl_sig, cl_err = [], [], [], [], [], [], []
        for j, sid in enumerate(ids):
            p = np.load(CACHE / sid / "pool.npz")
            ref = np.clip(p["cp"].astype(np.float64), *CLIP)
            P = np.stack([np.asarray(a[j], np.float64) for a in preds])
            m, sig = P.mean(0), P.std(0, ddof=1)
            err = m - ref
            sig_car.append(sig.mean())
            rel_car.append(np.sqrt((err ** 2).sum() / (ref ** 2).sum()))
            auc.append(auroc(sig, np.abs(err) > THR_ERR))
            r = assign_regions(p["xyz"], p["normal"], cfg)
            cnt = np.bincount(r, minlength=len(names)).astype(float)
            reg_sig.append(np.bincount(r, weights=sig, minlength=len(names)) / np.where(cnt > 0, cnt, np.nan))
            reg_mae.append(np.bincount(r, weights=np.abs(err), minlength=len(names)) / np.where(cnt > 0, cnt, np.nan))
            est = [cl(P[s], p["normal"][:, 2], p["area"], sid, np.ones(len(ref))) for s in range(3)]
            cl_sig.append(1000 * np.std(est, ddof=1))
            cl_err.append(1000 * abs(cl(m, p["normal"][:, 2], p["area"], sid, np.ones(len(ref))) - cl(ref, p["normal"][:, 2], p["area"], sid, np.ones(len(ref)))))
        rho_car = spearmanr(sig_car, rel_car)[0]
        auc_m = float(np.nanmean(auc))
        rs, rm = np.nanmean(reg_sig, 0), np.nanmean(reg_mae, 0)
        rho_reg = spearmanr(rs, rm, nan_policy="omit")[0]
        rows.append({"fold": f"{fold} ({held})", "cars": len(ids), "mean sigma": f"{np.mean(sig_car):.4f}", "mean ensemble MAE": f"{np.nanmean(rm):.4f}", "per-car Spearman (sigma, rel L2)": f"{rho_car:+.3f}",
                     f"AUROC (|err| > {THR_ERR})": f"{auc_m:.3f}", "region Spearman (11 regions)": f"{rho_reg:+.3f}"})
        reg_rows += [{"fold": fold, "region": n, "mean sigma": f"{rs[k]:.4f}", "MAE": f"{rm[k]:.4f}"} for k, n in enumerate(names)]
        cl_rows.append({"fold": fold, "mean sigma of C_L,p across seeds (counts)": f"{np.mean(cl_sig):.2f}", "mean |C_L,p error| of seed-mean (counts)": f"{np.mean(cl_err):.2f}", "ratio error / sigma": f"{np.mean(cl_err) / np.mean(cl_sig):.1f}",
                        "Spearman (sigma_CL, |error|) over cars": f"{spearmanr(cl_sig, cl_err)[0]:+.3f}"})
        verdict.append((rho_car >= GATE_RHO) and (auc_m >= GATE_AUC))
        print(rows[-1], flush=True)
    ok = all(verdict)
    sig_by_fold = {r["fold"][:3]: float(r["mean sigma"]) for r in rows}
    mae_by_fold = {r["fold"][:3]: float(r["mean ensemble MAE"]) for r in rows}
    text = ["# Seed-ensemble uncertainty gate (exploratory; auto-generated by `scripts/diagnosis/seed_spread_check.py`)", "",
            f"sigma = per-point std over M2 seeds 0-2; error = seed-mean prediction minus CFD (clipped Cp). Registered rule: the gate is *usable* only if the per-car Spearman is at least {GATE_RHO} and the mean AUROC at least {GATE_AUC} in all three folds.", "",
            "## 1. Per fold", "", md(rows), "",
            f"**Verdict against the registered rule: {'usable' if ok else 'NOT usable'}** (per fold: {', '.join(f'{f}: ' + ('pass' if v else 'fail') for f, v in zip(FOLDS, verdict))}).", "",
            f"Between folds: mean sigma E2A / E2B = {sig_by_fold['E2A'] / sig_by_fold['E2B']:.2f}, E2A / E2C = {sig_by_fold['E2A'] / sig_by_fold['E2C']:.2f}; mean MAE ratio E2A / E2B = {mae_by_fold['E2A'] / mae_by_fold['E2B']:.2f}, E2A / E2C = {mae_by_fold['E2A'] / mae_by_fold['E2C']:.2f}.", "",
            "## 2. Does the spread see the systematic pressure-lift error?", "", md(cl_rows), "",
            "## 3. By region (mean over cars)", "", md(reg_rows), ""]
    (ROOT / "reports" / "uncertainty_gate.md").write_text("\n".join(text), encoding="utf-8")


if __name__ == "__main__":
    main()
